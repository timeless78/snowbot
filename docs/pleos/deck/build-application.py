GRAY = RGBColor(0x55, 0x5B, 0x66)


def runs(par, text: str, size=10, bold=False):
    """**굵게** 표시를 나눠 run 으로 넣는다."""
    for i, part in enumerate(re.split(r"\*\*", text)):
        if part:
            r = par.add_run(part)
            r.bold = bold or (i % 2 == 1)
            r.font.size = Pt(size)


def borders(tbl):
    tblPr = tbl._tbl.tblPr
    b = OxmlElement("w:tblBorders")
    for edge in ("top", "left", "bottom", "right", "insideH", "insideV"):
        e = OxmlElement(f"w:{edge}")
        e.set(qn("w:val"), "single"); e.set(qn("w:sz"), "4"); e.set(qn("w:color"), "A0A6B0")
        b.append(e)
    # 스키마 순서: tblW, jc, … tblBorders, shd, tblLayout, tblCellMar, tblLook — tblLook 앞에 넣어야 Word 가 고치라고 묻지 않는다
    look = tblPr.find(qn("w:tblLook"))
    if look is not None:
        look.addprevious(b)
    else:
        tblPr.append(b)


def widths(tbl, total_mm=160):
    """안쪽 표 폭을 바깥 칸 안에 들게 맞춘다 (첫 열이 짧은 이름이면 좁게)."""
    n = len(tbl.columns)
    share = [1.0] * n
    if n >= 3:
        share[0] = 0.7
    unit = Mm(total_mm) / sum(share)
    for j, col in enumerate(tbl.columns):
        w = int(unit * share[j])
        tbl._tbl.tblGrid.gridCol_lst[j].w = w
        for c in col.cells:
            c.width = w


def shade(cell, fill="EEF1F5"):
    tcPr = cell._tc.get_or_add_tcPr()
    s = OxmlElement("w:shd"); s.set(qn("w:val"), "clear"); s.set(qn("w:color"), "auto"); s.set(qn("w:fill"), fill)
    tcPr.append(s)


def para(cell, first: list):
    """빈 첫 문단을 한 번 쓰고, 그 뒤로는 새 문단."""
    if first[0]:
        first[0] = False
        return cell.paragraphs[0]
    return cell.add_paragraph()


def fill(cell, blocks):
    first = [True]
    for kind, *rest in blocks:
        if kind == "lead":
            p = para(cell, first); runs(p, rest[0], 10.5, bold=True)
        elif kind == "p":
            p = para(cell, first); runs(p, rest[0])
        elif kind == "h":
            p = para(cell, first); p.paragraph_format.space_before = Pt(8); runs(p, rest[0], 10.5, bold=True)
        elif kind in ("ul", "ol"):
            for n, s in enumerate(rest[0], 1):
                p = para(cell, first)
                p.paragraph_format.left_indent = Mm(4); p.paragraph_format.first_line_indent = Mm(-4)
                runs(p, ("• " if kind == "ul" else f"{n}. ") + s)
        elif kind == "img":
            p = para(cell, first); p.paragraph_format.space_before = Pt(6)
            width = rest[2] if len(rest) > 2 else 158
            p.add_run().add_picture(str(FIGS / rest[0]), width=Mm(width))
            c = cell.add_paragraph(); r = c.add_run(rest[1]); r.font.size = Pt(9); r.font.color.rgb = GRAY
        elif kind == "t":
            rows = rest[0]
            para(cell, first)  # 표 앞 자리(빈 문단이 없으면 표가 셀 첫머리에 붙는다)
            t = cell.add_table(rows=len(rows), cols=len(rows[0]))
            t.alignment = WD_TABLE_ALIGNMENT.CENTER
            borders(t)
            widths(t)
            for i, row in enumerate(rows):
                for j, val in enumerate(row):
                    c = t.cell(i, j)
                    runs(c.paragraphs[0], val, 9, bold=(i == 0))
                    if i == 0:
                        shade(c)
            cell.add_paragraph()  # 표 뒤 간격
            first[0] = False


def set_text(par, text: str):
    rs = par.runs
    rs[0].text = text
    for r in rs[1:]:
        r.text = ""


